class _DuckDuckGoResultsParser(HTMLParser):
    """Extract ordinary DuckDuckGo HTML result titles, links and snippets."""
    def __init__(self):
        super().__init__()
        self.results = []
        self._current = None
        self._capture = None

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        classes = attrs.get("class", "").split()
        if tag == "a" and ("result__a" in classes or "result-link" in classes):
            self._current = {"title": "", "url": attrs.get("href", ""), "snippet": ""}
            self.results.append(self._current)
            self._capture = "title"
        elif self._current is not None and ("result__snippet" in classes or "result-snippet" in classes):
            self._capture = "snippet"

    def handle_endtag(self, tag):
        if tag == "a" and self._capture == "title":
            self._capture = None
        elif tag in ("div", "td") and self._capture == "snippet":
            self._capture = None

    def handle_data(self, data):
        if self._current is not None and self._capture:
            self._current[self._capture] += data


async def _search_without_gemini(query: str):
    """Search several independent public indexes; avoid relying on DuckDuckGo alone."""
    import asyncio
    import xml.etree.ElementTree as ET

    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/131.0 Safari/537.36",
        "Accept": "text/html,application/xhtml+xml,application/rss+xml,application/xml;q=0.9,*/*;q=0.8",
        "Accept-Language": "en-US,en;q=0.9",
    }
    providers = [
        ("Bing News/Web RSS", "https://www.bing.com/search", "rss"),
        ("DuckDuckGo HTML", "https://html.duckduckgo.com/html/", "html"),
        ("DuckDuckGo Lite", "https://lite.duckduckgo.com/lite/", "html"),
    ]
    failures = []

    for provider, endpoint, mode in providers:
        try:
            timeout = httpx.Timeout(14.0, connect=5.0, read=9.0, write=5.0, pool=5.0)
            async with httpx.AsyncClient(timeout=timeout, follow_redirects=True, headers=headers) as client:
                response = await client.get(endpoint, params={"q": query, "format": "rss"} if mode == "rss" else {"q": query})
            response.raise_for_status()
            sources = []

            if mode == "rss":
                root = ET.fromstring(response.content)
                for item in root.findall(".//item")[:8]:
                    title = (item.findtext("title") or "").strip()
                    url = (item.findtext("link") or "").strip()
                    snippet = (item.findtext("description") or "").strip()
                    if url.startswith(("https://", "http://")):
                        sources.append({"title": title or url, "url": url, "snippet": snippet})
            else:
                parser = _DuckDuckGoResultsParser()
                parser.feed(response.text)
                for item in parser.results:
                    raw_url = item["url"].strip()
                    parsed = urlparse(raw_url)
                    if parsed.netloc.endswith("duckduckgo.com"):
                        raw_url = parse_qs(parsed.query).get("uddg", [raw_url])[0]
                    if not raw_url.startswith(("https://", "http://")):
                        continue
                    sources.append({
                        "title": " ".join(item["title"].split()) or raw_url,
                        "url": raw_url,
                        "snippet": " ".join(item["snippet"].split()),
                    })
                    if len(sources) >= 8:
                        break

            unique = []
            seen = set()
            for source in sources:
                if source["url"] not in seen:
                    seen.add(source["url"])
                    unique.append(source)
                if len(unique) >= 8:
                    break

            if unique:
                lines = [f"Here is what I found about {query}:", ""]
                for index, source in enumerate(unique, 1):
                    lines.append(f"{index}. {source['title']}")
                    if source["snippet"]:
                        lines.append(source["snippet"])
                    lines.append("")
                return {
                    "answer": "\\n".join(lines).strip(),
                    "sources": unique,
                    "search_queries": [query],
                    "provider": provider,
                }
            failures.append(f"{provider}: no parseable results")
        except (httpx.HTTPError, ET.ParseError, ValueError) as exc:
            failures.append(f"{provider}: {type(exc).__name__}")
            print(f"Search provider {provider} failed: {exc}")

    # Last-chance structured encyclopedia search. This is still a real
    # live index request, but results are labelled as Wikipedia sources.
    try:
        async with httpx.AsyncClient(timeout=httpx.Timeout(12.0, connect=4.0), follow_redirects=True, headers=headers) as client:
            response = await client.get(
                "https://en.wikipedia.org/w/api.php",
                params={"action": "query", "list": "search", "srsearch": query, "srlimit": 8, "format": "json"},
            )
        response.raise_for_status()
        items = response.json().get("query", {}).get("search", [])
        sources = [{
            "title": item.get("title", "Wikipedia result"),
            "url": "https://en.wikipedia.org/wiki/" + item.get("title", "").replace(" ", "_"),
            "snippet": re.sub(r"<[^>]+>", "", item.get("snippet", "")),
        } for item in items if item.get("title")]
        if sources:
            return {
                "answer": "\\n".join(
                    [f"Live search results for {query} (Wikipedia index):"] +
                    [f"{i}. {x['title']}\\n{x['snippet']}\\n{x['url']}" for i, x in enumerate(sources, 1)]
                ),
                "sources": sources,
                "search_queries": [query],
                "provider": "Wikipedia Search",
            }
    except (httpx.HTTPError, ValueError) as exc:
        failures.append(f"Wikipedia: {type(exc).__name__}")
        print(f"Wikipedia fallback failed: {exc}")

    raise HTTPException(
        status_code=502,
        detail="Live search providers are temporarily unreachable. Please retry in a moment."
    )


async def _get_weather_answer(query: str):
    """Return current conditions and a short forecast using free Open-Meteo APIs."""
    import re
    place = re.sub(r"\b(weather|forecast|temperature|conditions|today|tomorrow|right now|current|please|what is|what's|in)\b", " ", query, flags=re.I)
    place = re.sub(r"\s+", " ", place).strip(" ,?.") or "Durban"
    try:
        async with httpx.AsyncClient(timeout=20, follow_redirects=True) as client:
            geo = await client.get("https://geocoding-api.open-meteo.com/v1/search", params={"name": place, "count": 1, "language": "en", "format": "json"})
            geo.raise_for_status()
            places = geo.json().get("results", [])
            if not places:
                return None
            city = places[0]
            forecast = await client.get("https://api.open-meteo.com/v1/forecast", params={
                "latitude": city["latitude"], "longitude": city["longitude"],
                "current": "temperature_2m,relative_humidity_2m,apparent_temperature,precipitation,weather_code,wind_speed_10m",
                "daily": "weather_code,temperature_2m_max,temperature_2m_min,precipitation_probability_max",
                "forecast_days": 2, "timezone": "auto"
            })
            forecast.raise_for_status()
            data = forecast.json()
        current, daily = data.get("current", {}), data.get("daily", {})
        code = int(current.get("weather_code", -1))
        descriptions = {0:"clear sky",1:"mainly clear",2:"partly cloudy",3:"overcast",45:"foggy",48:"rime fog",51:"light drizzle",53:"drizzle",55:"dense drizzle",61:"light rain",63:"moderate rain",65:"heavy rain",71:"light snow",73:"snow",75:"heavy snow",80:"rain showers",81:"moderate rain showers",82:"heavy rain showers",95:"thunderstorms",96:"thunderstorms with hail",99:"severe thunderstorms"}
        place_name = ", ".join(x for x in [city.get("name"), city.get("admin1"), city.get("country")] if x)
        lines = [f"Current weather in {place_name}:", f"{descriptions.get(code, 'conditions unavailable').capitalize()}, {current.get('temperature_2m', '—')}°C (feels like {current.get('apparent_temperature', '—')}°C).", f"Humidity: {current.get('relative_humidity_2m', '—')}%. Wind: {current.get('wind_speed_10m', '—')} km/h. Precipitation: {current.get('precipitation', '—')} mm."]
        dates = daily.get("time", [])
        for i in range(min(2, len(dates))):
            lines.append(f"{dates[i]}: {daily.get('temperature_2m_min', ['—']*2)[i]}–{daily.get('temperature_2m_max', ['—']*2)[i]}°C; rain chance up to {daily.get('precipitation_probability_max', ['—']*2)[i]}%.")
        return {"answer": "\n".join(lines), "sources":[{"title":"Open-Meteo weather forecast","url":"https://open-meteo.com/"}], "search_queries":[query], "provider":"Open-Meteo"}
    except (httpx.HTTPError, KeyError, ValueError, IndexError) as exc:
        print("Weather lookup failed: {}".format(exc))
        raise HTTPException(status_code=502, detail="I couldn't retrieve live weather for that location just now.")


@app.post("/search")
async def live_search(req: SearchRequest):
    """Search the live web; fall back to free search when Gemini quota is exhausted."""
    query = req.query.strip()
    if any(term in query.lower() for term in ("weather", "forecast", "temperature")):
        weather_result = await _get_weather_answer(query)
        if weather_result:
            return weather_result
    if GEMINI_API_KEY:
        payload = {
            "contents": [{
                "role": "user",
                "parts": [{"text": f"Search the live web for this query: {query}. Give a concise, useful answer based on current sources. Clearly distinguish verified facts from uncertainty."}]
            }],
            "tools": [{"google_search": {}}],
            "generationConfig": {"maxOutputTokens": 1200},
        }
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{GEMINI_MODEL}:generateContent"
        try:
            async with httpx.AsyncClient(timeout=httpx.Timeout(30.0, connect=8.0, read=22.0)) as client:
                response = await client.post(url, params={"key": GEMINI_API_KEY}, json=payload)
            if response.status_code >= 400:
                try:
                    error_data = response.json().get("error", {})
                    detail = error_data.get("message", "The search provider rejected the request.")
                    error_status = error_data.get("status", "")
                except Exception:
                    detail, error_status = "The search provider rejected the request.", ""
                is_quota_error = (
                    response.status_code == 429
                    or error_status == "RESOURCE_EXHAUSTED"
                    or "quota" in detail.lower()
                    or "rate limit" in detail.lower()
                )
                if not is_quota_error:
                    raise HTTPException(status_code=502, detail=f"Live search failed: {detail}")
                print("Gemini search quota exhausted; switching to free DuckDuckGo search.")
            else:
                data = response.json()
                candidates = data.get("candidates", [])
                candidate = candidates[0] if candidates else {}
                parts = candidate.get("content", {}).get("parts", [])
                answer = "".join(part.get("text", "") for part in parts).strip()
                if answer:
                    metadata = candidate.get("groundingMetadata", {})
                    sources = []
                    seen_urls = set()
                    for chunk in metadata.get("groundingChunks", []):
                        web_source = chunk.get("web", {})
                        uri = web_source.get("uri")
                        title = web_source.get("title") or uri
                        if uri and uri.startswith(("https://", "http://")) and uri not in seen_urls:
                            seen_urls.add(uri)
                            sources.append({"title": title, "url": uri})
                    return {"answer": answer, "sources": sources, "search_queries": metadata.get("webSearchQueries", [query]), "provider": "Gemini Google Search"}
                print("Gemini search returned no answer; switching to free DuckDuckGo search.")
        except HTTPException:
            raise
        except httpx.TimeoutException:
            print("Gemini search timed out; switching to free DuckDuckGo search.")
        except httpx.HTTPError:
            print("Gemini search network error; switching to free DuckDuckGo search.")

    return await _search_without_gemini(query)


@app.post("/code")
async def code(req: ChatRequest):
    """Dedicated coding route. Normal conversation continues to use the existing assistant."""
    if not ZAI_API_KEY:
        raise HTTPException(
            status_code=503,
            detail="The coding service is not configured yet. Add its API key in the server settings."
        )

    coding_prompt = """You are JARVIS's dedicated software engineer.
Solve the user's programming task directly and efficiently.
Prioritize correct, complete, runnable code over long explanations.
When modifying an existing project, respect the provided code and existing architecture.
When asked to fix code, return the complete corrected file or the exact complete replacement section, not vague instructions.
Use fenced code blocks for code so the app's copy-code controls can recognize them.
Keep explanations short. Never claim that you edited, committed, deployed, or tested files unless a tool actually did so.
Never reveal internal model, provider, API, key, or server implementation details."""

    messages = [{"role": "system", "content": coding_prompt}]
    for turn in req.conversation_history[-10:]:
        role = turn.get("role", "")
        content = turn.get("content", "")
        if role in ("user", "assistant") and isinstance(content, str) and content.strip():
            messages.append({"role": role, "content": content[:16000]})
    messages.append({"role": "user", "content": req.message})

    payload = {
        "messages": messages,
        "temperature": 0.2,
        "max_tokens": 8192,
        "stream": True,
        "thinking": {"type": "disabled"},
    }
    client = httpx.AsyncClient(timeout=httpx.Timeout(120.0, connect=12.0))
    upstream = None
    last_error = None
    # Both models are listed as free on Z.ai's standard API. If 4.7-Flash
    # returns provider overload (1305), automatically try 4.5-Flash.
    model_fallbacks = [ZAI_CODE_MODEL]
    if ZAI_CODE_MODEL != "glm-4.5-flash":
        model_fallbacks.append("glm-4.5-flash")

    try:
        for model_name in model_fallbacks:
            payload["model"] = model_name
            model_succeeded = False
            for attempt in range(2):
                request = client.build_request(
                    "POST",
                    "https://api.z.ai/api/paas/v4/chat/completions",
                    headers={
                        "Authorization": f"Bearer {ZAI_API_KEY}",
                        "Content-Type": "application/json",
                    },
                    json=payload,
                )
                upstream = await client.send(request, stream=True)
                if upstream.status_code < 400:
                    model_succeeded = True
                    break

                status = upstream.status_code
                error_body = await upstream.aread()
                provider_code = "unknown"
                provider_message = "No error message returned"
                try:
                    error_data = json.loads(error_body.decode("utf-8", errors="replace"))
                    provider_error = error_data.get("error", error_data)
                    if isinstance(provider_error, dict):
                        provider_code = str(provider_error.get("code", provider_error.get("type", "unknown")))[:80]
                        provider_message = str(provider_error.get("message", provider_error.get("detail", provider_error)))[:300]
                except (ValueError, TypeError):
                    provider_message = error_body.decode("utf-8", errors="replace")[:300] or provider_message

                await upstream.aclose()
                print("Coding provider rejected model {}: HTTP {} code={} message={}".format(
                    model_name, status, provider_code, provider_message
                ))

                # A 1305 is specifically reported by Z.ai as temporary model
                # overload. Move to the other free Flash model instead of
                # repeatedly sending the same request to the overloaded model.
                if provider_code == "1305":
                    last_error = (status, provider_code, provider_message)
                    break
                if status == 429 and attempt == 0:
                    await asyncio.sleep(2)
                    continue

                last_error = (status, provider_code, provider_message)
                break

            if model_succeeded:
                break
        else:
            model_succeeded = False

        if not model_succeeded:
            await client.aclose()
            raise HTTPException(
                status_code=502,
                detail="The coding service is temporarily unavailable. Please try again shortly."
            )
    except httpx.TimeoutException:
        await client.aclose()
        raise HTTPException(status_code=504, detail="The coding request took too long. Please try again.")
    except httpx.HTTPError:
        await client.aclose()
        raise HTTPException(status_code=502, detail="JARVIS could not reach the coding service.")
    except HTTPException:
        raise

    async def relay_code_stream():
        try:
            async for chunk in upstream.aiter_bytes():
                yield chunk
        finally:
            await upstream.aclose()
            await client.aclose()

    return StreamingResponse(
        relay_code_stream(),
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
    )


@app.post("/chat")
async def chat(req: ChatRequest):
    if not GEMINI_API_KEY:
        raise HTTPException(
            status_code=503,
            detail="JARVIS is online, but its assistant service is not configured. Please contact the administrator."
        )

    contents = []
    for turn in req.conversation_history[-12:]:
        role = turn.get("role", "")
        content = turn.get("content", "")
        if role in ("user", "assistant", "model") and isinstance(content, str) and content.strip():
            contents.append({
                "role": "model" if role in ("assistant", "model") else "user",
                "parts": [{"text": content[:12000]}],
            })
    contents.append({"role": "user", "parts": [{"text": req.message}]})

    payload = {
        "system_instruction": {"parts": [{"text": (
            JARVIS_SYSTEM_PROMPT
            + ("\\n\\nVOICE CALL MODE: Reply immediately and naturally in 1-3 short spoken sentences. "
               "Lead with the direct answer. Avoid long lists, markdown, preambles, and unnecessary explanations. "
               "Only give a detailed answer when the user explicitly asks for one."
               if req.voice_mode else "")
        )}]},
        "contents": contents,
        # Voice calls need a short spoken answer; normal chat retains its full output budget.
        "generationConfig": {"maxOutputTokens": 512 if req.voice_mode else 65536},
    }
    models_to_try = (GEMINI_MODEL,)
    last_provider_error = "The AI provider is temporarily unavailable."
    try:
        async with httpx.AsyncClient(timeout=180) as client:
            for model_index, model_name in enumerate(models_to_try):
                url = f"https://generativelanguage.googleapis.com/v1beta/models/{model_name}:generateContent"
                try:
                    response = await client.post(
                        url,
                        params={"key": GEMINI_API_KEY},
                        json=payload,
                    )
                except httpx.TimeoutException:
                    last_provider_error = f"{model_name} timed out."
                    print(f"Gemini model {model_name} timed out.")
                    if model_index < len(models_to_try) - 1:
                        continue
                    raise HTTPException(status_code=504, detail="JARVIS is taking too long to respond. Please try again.")

                if response.status_code >= 400:
                    try:
                        error_data = response.json().get("error", {})
                        detail = error_data.get("message", "AI provider rejected the request.")
                        error_status = error_data.get("status", "unknown")
                    except Exception:
                        detail, error_status = "AI provider rejected the request.", "unknown"
                    last_provider_error = detail
                    is_temporary = (
                        response.status_code in (429, 500, 502, 503, 504)
                        or error_status in ("RESOURCE_EXHAUSTED", "UNAVAILABLE", "INTERNAL")
                    )
                    print(f"Gemini model {model_name} failed: HTTP {response.status_code}; status={error_status}; detail={detail[:1000]}")
                    if is_temporary and model_index < len(models_to_try) - 1:
                        print(f"Switching JARVIS to Gemini fallback model {models_to_try[model_index + 1]}.")
                        continue
                    raise HTTPException(status_code=502, detail="JARVIS could not complete that response. Please try again.")

                data = response.json()
                candidates = data.get("candidates", [])
                parts = candidates[0].get("content", {}).get("parts", []) if candidates else []
                answer = "".join(part.get("text", "") for part in parts).strip()
                if answer:
                    if model_name != GEMINI_MODEL:
                        print(f"JARVIS response successfully generated using fallback model {model_name}.")
                    return {"response": answer}
                last_provider_error = "The AI provider returned an empty response."
                print(f"Gemini model {model_name} returned no text: {json.dumps(data, ensure_ascii=False)[:2000]}")
                if model_index < len(models_to_try) - 1:
                    continue
                raise HTTPException(status_code=502, detail=last_provider_error)
        raise HTTPException(status_code=502, detail="JARVIS could not complete that response. Please try again.")
    except HTTPException:
        raise
    except httpx.HTTPError:
        raise HTTPException(status_code=502, detail="JARVIS could not reach its assistant service.")

